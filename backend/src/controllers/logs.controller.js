// ────────────────────────────────────────────────────────────────────
// 手写区 1：依赖
// ────────────────────────────────────────────────────────────────────
const logsService=require('../services/logs.service')


// ════════════════════════════════════════════════════════════════════
// 段落 2 — 参考答案：listLogs — GET /
// ════════════════════════════════════════════════════════════════════
// async function listLogs(req, res, next) { try { ... } catch (e) { next(e) } }

// ────────────────────────────────────────────────────────────────────
// 手写区 2：listLogs
// ────────────────────────────────────────────────────────────────────
async function listLogs(req,res,next){
    try{
        const data=await logsService.listLogs(req.query)
        res.json(data)
    }catch(e){
        next(e)
    }
}


// ════════════════════════════════════════════════════════════════════
// 段落 3 — 参考答案：createLog — POST /
// ════════════════════════════════════════════════════════════════════

// ────────────────────────────────────────────────────────────────────
// 手写区 3：createLog
// ────────────────────────────────────────────────────────────────────
async function createLog(req,res,next){
    try{
        const data=await logsService.createLog(req.body)
        res.json(data)
    }catch(e){
        next(e)
    }
}


// ════════════════════════════════════════════════════════════════════
// 段落 4 — 参考答案：updateLog — PUT /:id
// ════════════════════════════════════════════════════════════════════

// ────────────────────────────────────────────────────────────────────
// 手写区 4：updateLog
// ────────────────────────────────────────────────────────────────────
async function updateLog(req,res,next){
    try{
        const id = parseInt(req.params.id, 10)
        const data=await logsService.updateLog(id,req.body)
        res.json(data)
    }catch(e){
        next(e)
    }
}


// ════════════════════════════════════════════════════════════════════
// 段落 5 — 参考答案：deleteLog — DELETE /:id
// ════════════════════════════════════════════════════════════════════

// ────────────────────────────────────────────────────────────────────
// 手写区 5：deleteLog
// ────────────────────────────────────────────────────────────────────

async function deleteLog(req,res,next){
    try{
        const id = parseInt(req.params.id, 10)
        const data=await logsService.deleteLog(id)
        res.json(data)
    }catch(e){
        next(e)
    }
}

